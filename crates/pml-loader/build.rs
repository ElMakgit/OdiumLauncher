//! Embeds the offline NeoForge archives into the launcher binary.
//!
//! The archives live in the `neoforge-mirror` GitHub release and are far too
//! large for git, so they are copied into `dist/neoforge-mirror/` before a
//! release build (`tools/fetch-offline-bundles.ps1`). A build without them is
//! still valid: the launcher then falls back to downloading the same archive,
//! exactly as before.
//!
//! Set `ODIUM_BUNDLES=require` to make a missing archive a build error. CI uses
//! it for release builds so a launcher is never shipped with a silently empty
//! offline mode.

use std::path::PathBuf;

/// Archives published under the `neoforge-mirror` tag, in a stable order.
const BUNDLES: &[&str] = &[
    "neoforge-21.1.248-offline.zip",
    "neoforge-1.20.1-47.1.79-offline.zip",
];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=ODIUM_BUNDLES");
    println!("cargo:rerun-if-env-changed=ODIUM_BUNDLE_DIR");

    let manifest_dir = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo always sets CARGO_MANIFEST_DIR"),
    );
    let bundle_dir = std::env::var_os("ODIUM_BUNDLE_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest_dir.join("../../dist/neoforge-mirror"));
    let required = std::env::var("ODIUM_BUNDLES").is_ok_and(|value| value == "require");

    // Watching the directory, not only the files, makes Cargo rerun this script
    // when a developer fetches the archives after a build without them.
    println!("cargo:rerun-if-changed={}", bundle_dir.display());

    let mut generated = String::from(
        "// Generated by build.rs. Offline NeoForge archives compiled into the binary.\n\
         pub static EMBEDDED_BUNDLES: &[(&str, &[u8])] = &[\n",
    );
    let mut found = 0usize;
    for file in BUNDLES {
        let path = bundle_dir.join(file);
        if !path.is_file() {
            if required {
                panic!(
                    "offline bundle is missing: {} — run tools/fetch-offline-bundles.ps1 \
                     or set ODIUM_BUNDLE_DIR",
                    path.display()
                );
            }
            continue;
        }
        let absolute = std::fs::canonicalize(&path).unwrap_or_else(|_| path.clone());
        // Forward slashes and a raw string keep Windows paths valid inside the
        // generated `include_bytes!`.
        let literal = absolute.to_string_lossy().replace('\\', "/");
        generated.push_str(&format!(
            "    (\"{file}\", include_bytes!(r\"{literal}\")),\n"
        ));
        println!("cargo:rerun-if-changed={}", absolute.display());
        found += 1;
    }
    generated.push_str("];\n");

    if found == 0 {
        println!(
            "cargo:warning=no offline NeoForge bundles in {}; the launcher will download them",
            bundle_dir.display()
        );
    } else {
        println!("cargo:warning=embedded {found} offline NeoForge bundle(s)");
    }

    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo always sets OUT_DIR"))
        .join("embedded_bundles.rs");
    std::fs::write(&out, generated).expect("write embedded_bundles.rs");
}
